    <h1>Política de privacidade — Assistente virtual da Barbearia Piloto</h1>
    <p class="meta">Última atualização: 14 de outubro de 2026</p>

    <p>Este assistente virtual (o "bot") atende clientes da Barbearia Piloto pelo Telegram, ajudando a consultar horários e marcar, remarcar ou confirmar agendamentos.</p>

    <h2>O que ele acessa</h2>
    <p>Pra marcar e consultar horários, o bot acessa a agenda do Google Calendar da Barbearia Piloto para:</p>
    <ul>
        <li>Consultar horários livres e ocupados (disponibilidade).</li>
        <li>Criar um evento quando um cliente confirma um agendamento.</li>
        <li>Ler e alterar a data/hora de um evento já existente, só quando o próprio cliente pede remarcação.</li>
    </ul>

    <h2>O que fica guardado em cada evento</h2>
    <ul>
        <li>Nome do cliente e serviço escolhido, no título do evento.</li>
        <li>Telefone do cliente e canal de contato, na descrição do evento.</li>
    </ul>

    <h2>Com quem isso é compartilhado</h2>
    <p>Nada é compartilhado com terceiros. O acesso à agenda é usado exclusivamente pelo assistente virtual da própria Barbearia Piloto, só para marcar e consultar os agendamentos dos clientes que conversam com o bot.</p>

